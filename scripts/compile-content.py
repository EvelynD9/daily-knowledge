"""Build the additional card bundle from the maintained multilingual source rows."""
from pathlib import Path
import json
root=Path(__file__).resolve().parent.parent
cards=json.loads((root/'scripts/new-cards.json').read_text())
for lang in ['el','ru','ro']:
    translations=json.loads((root/f'scripts/new-{lang}.json').read_text())
    assert set(translations)=={card['id'] for card in cards}
    for card in cards:card[lang]=translations[card['id']]
for card in cards:
    assert card['answer'] in [0,1,2]
    for lang in ['en','el','ru','ro']:
        row=card[lang]
        assert len(row)==8 and len(row[6])==3
        assert all(isinstance(value,str) and value.strip() for value in row[:6]+row[6]+[row[7]])
loader='''
for(const record of EXTRA_CARDS){
  const row=record.en;
  CARDS.push({id:record.id,topic:record.topic,title:row[0],hook:row[1],concept:row[2],example:row[3],takeaway:row[4],sourceName:record.sourceName,sourceUrl:record.sourceUrl});
  QUIZZES[record.id]={question:row[5],options:row[6],answer:record.answer,feedback:row[7]};
  CONTENT_EL[record.id]=record.el;CONTENT_RU[record.id]=record.ru;CONTENT_RO[record.id]=record.ro;
}
'''
(root/'extra-content.js').write_text('/* Generated by scripts/compile-content.py. */\nconst EXTRA_CARDS='+json.dumps(cards,ensure_ascii=False,separators=(',',':'))+';\n'+loader)
print(f'Compiled {len(cards)} additional cards in four languages')
